"""The draft plan and its four cards (ticket, branch, commit, PR), built in code.

The plan holds everything a card shows: the destination repository and base branch (from tool output,
never from the user's words), the test file as fetched, the patch (regenerated by patch.py from that file
whenever the ticket number or the skip note changes), the ticket and PR text. Each card's `Approval` binds
its one tool, its target and its content for the send guard.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Mapping
from dataclasses import asdict, dataclass, field, fields, replace
from typing import Any

import patch as patcher
from history import Flaky
from nasiko_hitl import question_metadata
from send_guard import Approval

CREATE, SKIP, APPROVE = "Create issue", "Skip", "Approve"
_BRANCH_NAME = re.compile(r"^(?!-)(?!.*\.\.)(?!.*//)[A-Za-z0-9._/-]{1,100}(?<![/.])$")
_YES = frozenset({"approve", "approved", "yes", "y", "ok", "okay", "create", "create issue", "comment", "go",
                  "do it", "send", "authorized"})
_NO = frozenset({"skip", "no", "n", "cancel", "stop", "deny", "denied", "reject", "decline", "don't", "dont"})


@dataclass(frozen=True)
class Plan:
    owner: str
    repo: str
    base: str
    base_sha: str
    flaky: dict
    path: str = ""
    file_sha: str = ""
    original: str = ""
    scope: str = ""                  # the pytest class, when the id names one
    ticket: str = "TBD"
    ticket_url: str = ""
    existing_issue: str = ""
    issue_body: str = ""
    note: str = ""                   # the user's skip note (commit card edit)
    branch: str = ""
    pr_title: str = ""
    pr_body_override: str = ""
    patch_error: str = ""
    tools: dict = field(default_factory=dict)   # issue | comment | branch | commit | pr → tool name
    bound: dict = field(default_factory=dict)   # what the branch card showed: branch, base, path, diff hash

    @property
    def item(self) -> Flaky:
        return Flaky.from_dict(self.flaky)

    @property
    def full(self) -> str:
        return f"{self.owner}/{self.repo}"

    def patch(self) -> patcher.Patch | str:
        if self.patch_error:
            return self.patch_error
        return patcher.make(self.path, self.original, self.item.name, self.ticket, self.note, self.scope)

    @property
    def can_pr(self) -> bool:
        return isinstance(self.patch(), patcher.Patch) and all(self.tools.get(k) for k in ("branch", "commit", "pr"))

    @property
    def issue_title(self) -> str:
        return f"Flaky test: {self.item.test}"

    @property
    def commit_message(self) -> str:
        return f"Skip flaky test {self.item.name} ({self.ticket})"

    @property
    def title(self) -> str:
        return self.pr_title or f"Skip flaky test {self.item.name}"

    def default_issue_body(self) -> str:
        f = self.item
        lines = [(f"`{f.test}` fails intermittently in CI: failed {f.k} of the last {f.n} runs (at least "
                  f"{f.rate_pct}%), passed on rerun of {f.rerun_flip} commit(s)."), "", "Evidence runs:"]
        lines += [f"- run {e.run} ({e.sha}, {e.date}, {e.attempt})" + (f" {e.url}" if e.url else "")
                  for e in f.evidence]
        line = next((e.line for e in f.evidence if e.line), "")
        if line:
            lines += ["", "Log line:", "```", line, "```"]
        return "\n".join(lines)

    @property
    def body(self) -> str:
        return self.issue_body or self.default_issue_body()

    @property
    def pr_body(self) -> str:
        if self.pr_body_override:
            return self.pr_body_override
        f = self.item
        ticket = f"{self.ticket} {self.ticket_url}".strip() if self.ticket != "TBD" else "TBD (no ticket was created)"
        return (f"Skips the flaky test `{f.test}` (failed {f.k} of the last {f.n} CI runs, at least {f.rate_pct}%).\n\n"
                f"Ticket: {ticket}\n\nThe change adds one skip marker in `{self.path}` and nothing else. "
                "Remove it once the ticket is fixed.")

    def binding(self) -> dict:
        p = self.patch()
        digest = hashlib.sha256(p.patched.encode()).hexdigest() if isinstance(p, patcher.Patch) else ""
        return {"branch": self.branch, "base": self.base, "path": self.path, "diff": digest}

    def to_dict(self) -> dict:
        return asdict(self)

    @staticmethod
    def from_dict(data: Mapping[str, Any]) -> Plan:
        names = {f.name for f in fields(Plan)}
        values = {k: v for k, v in dict(data).items() if k in names}
        return Plan(**values)


def branch_name(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.casefold()).strip("-")[:50] or "test"
    return f"flaky/{slug}"


def valid_branch(name: str) -> bool:
    return bool(_BRANCH_NAME.match(name or ""))


def approval(plan: Plan, kind: str) -> Approval:
    p = plan.patch()
    values: dict[str, str]
    alternates: dict[str, tuple[str, ...]] = {}
    if kind == "issue":
        values = {"title": plan.issue_title, "body": plan.body}
    elif kind == "comment":
        values = {"number": plan.existing_issue, "body": plan.body}
    elif kind == "branch":
        values, alternates = {"ref": plan.branch, "from": plan.base_sha or plan.base}, {"from": (plan.base,)}
    elif kind == "commit":
        values = {"branch": plan.branch, "path": plan.path, "content": p.patched if isinstance(p, patcher.Patch) else "",
                  "message": plan.commit_message, "sha": plan.file_sha}
    else:
        values = {"head": plan.branch, "base": plan.base, "title": plan.title, "body": plan.pr_body}
    return Approval(kind, plan.tools.get(kind, ""), plan.owner, plan.repo, values, alternates)


def card(plan: Plan, stage: str, preface: str = "") -> tuple[str, dict]:
    """(text, question metadata) for one card."""
    if stage == "ticket":
        if plan.existing_issue:
            header, yes = f"Comment on existing issue #{plan.existing_issue} in {plan.full}?", f"Comment on #{plan.existing_issue}"
            text = f"Issue #{plan.existing_issue} already tracks this test. Comment:\n\n{plan.body}"
        else:
            header, yes = f"Create issue in {plan.full}?", CREATE
            text = f"Title: {plan.issue_title}\n\n{plan.body}"
        hint = "Reply with an option, or type your own text to use as the body instead."
    else:
        header, text = _pr_card(plan, stage)
        yes, hint = APPROVE, _HINTS[stage]
    hitl = question_metadata(_cut(header), [(yes, "Make exactly this one write."), (SKIP, _SKIP_HELP[stage])])
    body = "\n\n".join(x for x in (preface, text, hint) if x)
    return body, hitl


_HINTS = {"branch": "Reply Approve or Skip, or type a different branch name.",
          "commit": "Reply Approve or Skip, or type `reason: <text>` to change the skip reason.",
          "pr": "Reply Approve or Skip, or type `title: <text>` or a new PR body."}
_SKIP_HELP = {"ticket": "No issue; the skip marker will say TBD.", "branch": "Write nothing for the pull request.",
              "commit": "Stop here; the branch stays without a commit.", "pr": "Stop here; no pull request is opened."}


def _pr_card(plan: Plan, stage: str) -> tuple[str, str]:
    p = plan.patch()
    diff = p.diff if isinstance(p, patcher.Patch) else ""
    if stage == "branch":
        header = f"Create branch `{plan.branch}` in `{plan.full}` from `{plan.base}`?"
        text = (f"Plan (each step gets its own card):\n1. Create branch `{plan.branch}` from `{plan.base}`\n"
                f"2. Commit `{plan.path}`:\n```diff\n{diff}\n```\n3. Open a draft PR `{plan.title}`:\n\n{plan.pr_body}")
    elif stage == "commit":
        header = f"Commit `{plan.path}` to `{plan.branch}`?"
        text = f"Commit message: {plan.commit_message}\n\n```diff\n{diff}\n```"
    else:
        header = f"Open PR `{plan.title}` from `{plan.branch}` to `{plan.base}`?"
        text = f"Draft pull request in {plan.full}\nTitle: {plan.title}\n\n{plan.pr_body}"
    return header, text


def _cut(header: str) -> str:
    data = header.encode()
    return header if len(data) <= 200 else data[:196].decode(errors="ignore") + "...?"


def interpret(answer: str) -> tuple[str, str]:
    """(approve | skip | edit, text). Empty and unclear refusals are skip: nothing is written by default."""
    text = (answer or "").strip()
    word = text.casefold().rstrip(".!")
    if not word or word in _NO:
        return "skip", ""
    if word in _YES or word.startswith("comment on #"):
        return "approve", ""
    return "edit", text


def apply_edit(plan: Plan, stage: str, text: str) -> tuple[Plan, str]:
    """The plan with the edit applied, or the unchanged plan and why it could not be applied."""
    if stage == "ticket":
        return replace(plan, issue_body=text), ""
    if stage == "branch":
        name = text.strip().strip("`").removeprefix("refs/heads/")
        if not valid_branch(name):
            return plan, f"`{name[:60]}` isn't a valid branch name, so the card is unchanged."
        return replace(plan, branch=name), ""
    if stage == "commit":
        m = re.match(r"^reason\s*:\s*(.+)$", text.strip(), re.IGNORECASE | re.DOTALL)
        if not m:
            return plan, "Here I can only change the skip reason (type `reason: <text>`), so the card is unchanged."
        edited = replace(plan, note=m.group(1).strip())
        return (edited, "") if isinstance(edited.patch(), patcher.Patch) else (plan, "That reason did not verify.")
    m = re.match(r"^title\s*:\s*(.+)$", text.strip(), re.IGNORECASE)
    if m:
        return replace(plan, pr_title=" ".join(m.group(1).split())[:200]), ""
    return replace(plan, pr_body_override=text.strip()), ""


def copy_text(plan: Plan) -> str:
    """Everything the user needs to make the change by hand (no write tool, or a block stance)."""
    p = plan.patch()
    out = []
    if plan.ticket == "TBD":
        out.append(f"Issue title: {plan.issue_title}\n\n{plan.body}")
    if isinstance(p, patcher.Patch):
        out.append(f"Branch: {plan.branch} (from {plan.base})\n\n```diff\n{p.diff}\n```\n\n"
                   f"Commit message: {plan.commit_message}\n\nPR title: {plan.title}\n\n{plan.pr_body}")
    return "\n\n---\n\n".join(out)
