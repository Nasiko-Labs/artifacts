"""Pure: read the model's JSON answer for each command, post-check it in code, render PR-Agent-style
markdown.

The post-check is the guarantee, not the prompt: a finding or suggestion that cites a file the model
was not shown is dropped, numbers are clamped to their ranges, list lengths are capped.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Collection, Mapping
from typing import Any

from commands import Command, PrRef
from diff import CompressedDiff
from pr_info import PrInfo
from prompts import MAX_KEY_ISSUES, MAX_SUGGESTIONS

_CODE_FENCE = re.compile(r"^```(?:json)?\s*|\s*```$")
_PR_TYPES = ("Bug fix", "Tests", "Enhancement", "Documentation", "Other")
MAX_WALKTHROUGH_FILES = 30
FOOTER = "_Generated by pr-agent on Nasiko._"


def load_json_object(text: str) -> dict | None:
    body = _CODE_FENCE.sub("", (text or "").strip())
    start, end = body.find("{"), body.rfind("}")
    if start < 0 or end <= start:
        return None
    try:
        data = json.loads(body[start:end + 1])
    except ValueError:
        return None
    return data if isinstance(data, dict) else None


def render(command: Command, answer: Mapping[str, Any], pr: PrRef, info: PrInfo, diff: CompressedDiff,
           question: str = "") -> str | None:
    """The markdown result, or None when the answer is not the agreed shape for `command`."""
    known = frozenset(diff.included)
    renderers: dict[Command, Callable[[], str | None]] = {
        "describe": lambda: _describe(answer, pr, info, known),
        "review": lambda: _review(answer, pr, known),
        "improve": lambda: _improve(answer, pr, known),
        "ask": lambda: _ask(answer, pr, question),
    }
    body = renderers[command]()
    if body is None:
        return None
    note = diff.coverage_note()
    return f"{body}\n\n> Coverage: {note}" if note else body


# --- describe ----------------------------------------------------------------------------------

def _describe(answer: Mapping[str, Any], pr: PrRef, info: PrInfo, known: Collection[str]) -> str | None:
    title = _text(answer.get("title"))
    summary = [s for s in (_text(b) for b in _list(answer.get("summary"))) if s]
    if not title or not summary:
        return None
    types = list(dict.fromkeys(t for t in (_text(x) for x in _list(answer.get("types"))) if t in _PR_TYPES))
    types = types or ["Other"]
    files = [f for f in _list(answer.get("files")) if isinstance(f, Mapping) and _text(f.get("filename")) in known]
    lines = [
        f"## PR Description: [{pr.slug}]({pr.url})",
        "",
        f"**Title:** {title}",
        f"**PR Type:** {', '.join(types)}",
    ]
    if info.title and info.title != title:
        lines.append(f"**Current title:** {info.title}")
    lines += ["", "### Description", *(f"- {s}" for s in summary)]
    if files:
        lines += ["", "### Changes walkthrough", "", "| File | Label | Changes |", "|---|---|---|"]
        lines += [f"| `{_cell(f.get('filename'))}` | {_cell(f.get('label')) or '-'} | {_cell(f.get('change_title'))} |"
                  for f in files[:MAX_WALKTHROUGH_FILES]]
    return "\n".join(lines)


# --- review ------------------------------------------------------------------------------------

def _review(answer: Mapping[str, Any], pr: PrRef, known: Collection[str]) -> str | None:
    if "key_issues" not in answer or "estimated_effort" not in answer:
        return None
    effort = _clamp(answer.get("estimated_effort"), 1, 5)
    tests = "Yes" if _text(answer.get("relevant_tests")).lower().startswith("y") else "No"
    security = _text(answer.get("security_concerns")) or "No"
    issues = [i for i in _list(answer.get("key_issues"))
              if isinstance(i, Mapping) and _text(i.get("file")) in known and _text(i.get("content"))]
    split = _text(answer.get("can_be_split"))
    lines = [
        f"## PR Reviewer Guide: [{pr.slug}]({pr.url})",
        "",
        "| | |",
        "|---|---|",
        f"| **Estimated effort to review [1-5]** | {effort} {_bar(effort)} |",
        f"| **Relevant tests** | {tests} |",
        f"| **Security concerns** | {_cell(security)} |",
    ]
    if split and split.lower() != "no":
        lines.append(f"| **Can be split** | {_cell(split)} |")
    lines += ["", "### Key issues to review"]
    if not issues:
        lines.append("No key issues found in the analyzed changes.")
    for issue in issues[:MAX_KEY_ISSUES]:
        lines.append(f"- **{_text(issue.get('header')) or 'Issue'}** ({_where(issue)}): {_text(issue.get('content'))}")
    return "\n".join(lines)


def _bar(effort: int) -> str:
    return "(" + "#" * effort + "." * (5 - effort) + ")"


# --- improve -----------------------------------------------------------------------------------

def _improve(answer: Mapping[str, Any], pr: PrRef, known: Collection[str]) -> str | None:
    if "suggestions" not in answer or not isinstance(answer.get("suggestions"), list):
        return None
    kept = [s for s in answer["suggestions"]
            if isinstance(s, Mapping) and _text(s.get("file")) in known and _text(s.get("improved_code"))]
    kept.sort(key=lambda s: -_clamp(s.get("importance"), 1, 10))
    lines = [f"## PR Code Suggestions: [{pr.slug}]({pr.url})", ""]
    if not kept:
        lines.append("No code suggestions for the analyzed changes.")
        return "\n".join(lines)
    lines += ["| # | Category | Suggestion | Where | Importance |", "|---|---|---|---|---|"]
    top = kept[:MAX_SUGGESTIONS]
    lines += [f"| {n} | {_cell(s.get('label')) or 'enhancement'} | {_cell(s.get('summary'))} | {_where(s)} | "
              f"{_clamp(s.get('importance'), 1, 10)} |" for n, s in enumerate(top, start=1)]
    for n, s in enumerate(top, start=1):
        language = _text(s.get("language")).lower()
        lines += ["", f"### {n}. {_text(s.get('summary')) or 'Suggestion'}", "", _text(s.get("content")), "",
                  f"`{_text(s.get('file'))}` {_lines(s)}"]
        existing = _text(s.get("existing_code"))
        if existing:
            lines += ["", "Existing code:", f"```{language}", existing, "```"]
        lines += ["", "Improved code:", f"```{language}", _text(s.get("improved_code")), "```"]
    return "\n".join(lines)


# --- ask ---------------------------------------------------------------------------------------

def _ask(answer: Mapping[str, Any], pr: PrRef, question: str) -> str | None:
    text = _text(answer.get("answer"))
    if not text:
        return None
    return f"## Ask: [{pr.slug}]({pr.url})\n\n**Question:** {question}\n\n**Answer:**\n{text}"


# --- shared ------------------------------------------------------------------------------------

def comment_body(report: str) -> str:
    return f"{report}\n\n{FOOTER}"


def _where(item: Mapping[str, Any]) -> str:
    return f"`{_text(item.get('file'))}` {_lines(item)}".strip()


def _lines(item: Mapping[str, Any]) -> str:
    start, end = _int_or_none(item.get("start_line")), _int_or_none(item.get("end_line"))
    if start is None:
        return ""
    return f"L{start}" if end is None or end <= start else f"L{start}-L{end}"


def _int_or_none(value: Any) -> int | None:
    try:
        number = int(value)
    except (TypeError, ValueError):
        return None
    return number if number > 0 else None


def _clamp(value: Any, low: int, high: int) -> int:
    number = _int_or_none(value) or low
    return max(low, min(high, number))


def _list(value: Any) -> list:
    return value if isinstance(value, list) else []


def _text(value: Any) -> str:
    return str(value).strip() if value is not None else ""


def _cell(value: Any) -> str:
    """Safe inside a markdown table cell."""
    return _text(value).replace("|", "\\|").replace("\n", " ")
