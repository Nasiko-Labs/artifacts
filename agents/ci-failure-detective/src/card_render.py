"""Pure: the verdict card shown in chat, the pull request comment (markdown) and the flaky-test ticket,
all built in code from checked facts."""

from __future__ import annotations

import re

import classify
import history as h
from analysis import Analysis, Report
from verdict import Verdict

MAX_LOG_LINES = 15
FOOTER = "_Generated by the CI Failure Detective on Nasiko._"
TICKET_LABEL = "flaky-test"
_MENTION = re.compile(r"@(?=[A-Za-z0-9_-])")


def strip_mentions(text: str) -> str:
    """No `@login` survives outside an explicitly approved mention."""
    return _MENTION.sub("", text or "")


def verdict_line(a: Analysis, v: Verdict) -> str:
    top = a.narrowed.culprit if a.narrowed else None
    if v.kind == "infra":
        return "INFRA — the job failed because of the CI environment; a rerun should pass."
    if v.kind == "real":
        if top is not None and v.culprit_sha:
            c = top.commit
            return f"REAL — likely culprit {c.sha[:7]} \"{c.subject}\" by {c.author}"
        return f"REAL — {a.narrowed.note if a.narrowed and a.narrowed.note else 'culprit not narrowed'}"
    rate = h.rate_sentence(a.flaky) if a.flaky else "has no run history"
    if v.kind == "flaky":
        return f"FLAKY — {_subject(a)} {rate}"
    return f"UNCLEAR — {_subject(a)} {rate}; not enough history to call it"


def _subject(a: Analysis) -> str:
    return f"`{a.test_id}`" if a.test_id else f"job {a.job.name}"


def _where(a: Analysis) -> str:
    return f"PR #{a.pr.number}" if a.pr else (a.run.branch or "?")


def evidence_lines(a: Analysis, v: Verdict) -> list[str]:
    top = a.narrowed.culprit if a.narrowed else None
    lines = list(top.evidence) if top is not None and v.kind != "infra" else []
    if v.kind == "unclear" and top is not None and top.score >= 1:
        lines = [f"closest match {top.commit.sha[:7]}: {e}" for e in top.evidence]
    if a.flaky and a.flaky.boundary and v.kind == "real":
        b = a.flaky.boundary
        lines.append(f"last green run at {b.last_green_sha[:7]}; red from {b.sha[:7]} on")
    return lines


def log_lines(a: Analysis, v: Verdict) -> list[str]:
    lines = [line for line in a.excerpt.splitlines() if line.strip()]
    if v.log_quote and v.log_quote not in "\n".join(lines[-MAX_LOG_LINES:]):
        return [v.log_quote, *lines[-(MAX_LOG_LINES - 1):]]
    return lines[-MAX_LOG_LINES:]


def card(a: Analysis, v: Verdict) -> str:
    run = a.run
    link = f" {run.url}" if run.url else ""
    since = a.flaky.since.date().isoformat() if a.flaky and a.flaky.since else "n/a"
    fix = f"`{v.fix.file}:{v.fix.line}` — {v.fix.change}" if v.fix else "none obvious"
    history_line = (f"{a.flaky.n} runs checked ({a.flaky.k} red for this test, {a.flaky.u} not inspected) since {since}"
                    if a.flaky else "not checked")
    parts = [
        (f"CI failure · {a.target.repo_full} · {run.workflow} / {a.job.name} · run {run.run_id}{link} · "
         f"{run.head_sha[:7]} on {_where(a)}"),
        f"Verdict: {verdict_line(a, v)}",
        f"Class: {classify.LABELS.get(v.failure_class, v.failure_class)} · Failing: {a.test_id or 'test id unknown'}",
        f"Why: {v.summary}",
    ]
    evidence = evidence_lines(a, v)
    if evidence:
        parts.append("Evidence:\n" + "\n".join(f"- {e}" for e in evidence))
    logs = log_lines(a, v)
    parts.append("Log:\n" + ("\n".join(f"  > {line}" for line in logs) if logs else "  (no log text available)"))
    parts += [f"Suggested fix: {fix}", f"History: {history_line}"]
    if a.other_jobs:
        parts.append("Other failed jobs: " + ", ".join(a.other_jobs) + " (say 'check job <name>')")
    if a.notes:
        parts.append("Coverage: " + " ".join(dict.fromkeys(a.notes)))
    parts.append(_offer(a, v))
    return "\n".join(p for p in parts if p)


def _offer(a: Analysis, v: Verdict) -> str:
    offers = []
    if a.pr is not None:
        offers.append("\"post it\" to comment this on the pull request")
    if v.kind == "flaky":
        offers.append("\"open the flaky ticket\" to file it as a flaky test")
    return ("Say " + " or ".join(offers) + "; nothing is written until you approve the exact text.") if offers else ""


def comment_markdown(a: Analysis, v: Verdict) -> str:
    run = a.run
    logs = "\n".join(log_lines(a, v)).replace("```", "'''")
    fix = f"`{v.fix.file}:{v.fix.line}` — {strip_mentions(v.fix.change)}" if v.fix else "none obvious"
    evidence = "".join(f"\n- {strip_mentions(e)}" for e in evidence_lines(a, v))
    rate = f"\n**History:** the job {h.rate_sentence(a.flaky)}." if a.flaky else ""
    return (f"### CI failure: {run.workflow} / {strip_mentions(a.job.name)}\n"
            f"**Run:** {run.url or run.run_id} · commit `{run.head_sha[:7]}`\n"
            f"**Verdict:** {strip_mentions(verdict_line(a, v))}\n"
            f"**Class:** {classify.LABELS.get(v.failure_class, v.failure_class)} · **Failing:** "
            f"`{a.test_id or 'test id unknown'}`\n"
            f"**Why:** {strip_mentions(v.summary)}{evidence}{rate}\n\n```\n{logs}\n```\n"
            f"**Suggested fix:** {fix}\n\n{FOOTER}")


def ticket_title(a: Analysis) -> str:
    return f"Flaky test: {a.test_id or a.job.name}"


def ticket_body(a: Analysis, v: Verdict) -> str:
    rows = sorted(a.rows, key=lambda r: r.created_at)
    reds = [r for r in rows if r.state == "red"]
    greens = [r for r in rows if r.state == "green"]
    runs = "\n".join(f"- {r.state}: run {r.run_id} at {r.sha[:7]} {r.url}".rstrip() for r in rows[-10:])
    logs = "\n".join(log_lines(a, v)).replace("```", "'''")
    return (f"`{a.test_id or a.job.name}` in {a.run.workflow} / {strip_mentions(a.job.name)} "
            f"{h.rate_sentence(a.flaky) if a.flaky else ''}.\n\n"
            f"Last green: {greens[-1].sha[:7] if greens else 'none seen'} · last red: "
            f"{reds[-1].sha[:7] if reds else a.run.head_sha[:7]}\n\nRuns:\n{runs}\n\n```\n{logs}\n```\n\n{FOOTER}")


def ticket_update(a: Analysis) -> str:
    rate = h.rate_sentence(a.flaky) if a.flaky else "failed again"
    return f"Seen again: `{a.test_id or a.job.name}` {rate}. Latest failure: {a.run.url or a.run.run_id}\n\n{FOOTER}"


def report(a: Analysis, v: Verdict, card_text: str) -> Report:
    top = a.narrowed.culprit if a.narrowed else None
    login = top.commit.author_login if top is not None and v.culprit_sha else ""
    return Report(owner=a.target.owner, repo=a.target.repo, pr_number=a.pr.number if a.pr else "",
                  run_id=a.run.run_id, run_url=a.run.url, workflow=a.run.workflow, job_name=a.job.name,
                  sha=a.run.head_sha, verdict=v.kind, culprit_sha=v.culprit_sha, culprit_login=login,
                  test_id=a.test_id, rate=h.rate_sentence(a.flaky) if a.flaky else "", card=card_text,
                  excerpt=a.excerpt, comment=comment_markdown(a, v), ticket_title=ticket_title(a),
                  ticket_body=ticket_body(a, v), ticket_update=ticket_update(a), other_jobs=a.other_jobs,
                  target=a.target.to_dict())
