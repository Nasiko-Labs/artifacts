"""Pure: everything the user sees, built in code from the checked Review: the chat card (markdown, no raw
HTML, no images, links only from tool output), the criteria and similar-PR views, the comment body that
may be posted, and the envelope (`summary, items, confidence, needs_human, comments, ticket_alignment`)."""

from __future__ import annotations

import json
import re
from collections.abc import Sequence

from report import Review
from verify import Comment

FOOTER = "_Generated by the Context-Aware PR Reviewer on Nasiko._"
OFFER = "Say \"post it\" to comment this on the pull request; nothing is written until you approve the exact text."
_MENTION = re.compile(r"@(?=[A-Za-z0-9_-])")
_LABELS = {"aligned": "ALIGNED", "partial": "PARTIAL", "misaligned": "MISALIGNED", "no_ticket": "NO TICKET",
           "unclear": "UNCLEAR"}
_STATUS = {"met": "met", "partial": "partial", "not_found": "not found"}


def clean(text: str) -> str:
    """No raw HTML: angle brackets are escaped for markdown."""
    return (text or "").replace("<", "\\<").replace(">", "\\>")


def strip_mentions(text: str) -> str:
    return _MENTION.sub("", text or "")


def focused(r: Review, focus: str = "") -> tuple[Comment, ...]:
    wanted = focus or r.focus
    comments = r.comment_objs()
    return tuple(c for c in comments if c.category == wanted) if wanted else comments


def _where(c: Comment) -> str:
    if not c.file:
        return "PR-level"
    return f"`{c.file}:{c.line}`" if c.line else f"`{c.file}`"


def comment_lines(comments: Sequence[Comment]) -> list[str]:
    out = []
    for c in comments:
        out.append(f"- [{c.severity}] {_where(c)} ({c.category}): {clean(c.comment)}")
        extra = []
        if c.quote:
            extra.append("`" + c.quote.replace("`", "'") + "`")
        if c.precedent:
            extra.append(f"precedent: {c.precedent}")
        if extra:
            out.append("  > " + " · ".join(extra))
    return out


def criteria_line(r: Review) -> str:
    parts = []
    for c in r.criteria_objs():
        status = _STATUS.get(c.status, c.status)
        if c.status == "not_found":
            parts.append(f"{c.id} {status}: \"{clean(c.text)}\"")
        elif c.evidence:
            parts.append(f"{c.id} {status} ({', '.join(f'{f}:{n}' for f, n in c.evidence[:2])})")
        else:
            parts.append(f"{c.id} {status}")
    return "Criteria: " + " · ".join(parts) if parts else ""


def headline(r: Review) -> str:
    title = f" \"{clean(r.title)}\"" if r.title else ""
    against = f" · against {r.ticket}" if r.ticket else " · no ticket"
    count = f" ({r.coverage} criteria)" if r.criteria else ""
    return f"**PR review** · {r.pr_label}{title}{against} · alignment: **{_LABELS.get(r.label, r.label)}**{count}"


def _counts(comments: Sequence[Comment]) -> str:
    by = {s: sum(1 for c in comments if c.severity == s) for s in ("blocker", "suggestion", "nit")}
    parts = [f"{n} {s}{'s' if n != 1 else ''}" for s, n in by.items() if n]
    return ", ".join(parts) or "none"


def coverage_line(r: Review) -> str:
    skipped = ", ".join(f"{p} ({why})" for p, why in r.skipped)
    parts = [f"{len(r.reviewed)} file{'s' if len(r.reviewed) != 1 else ''} reviewed"]
    if skipped:
        parts.append(f"skipped {skipped}")
    return "Coverage: " + "; ".join(parts) + "." + "".join(f" {n}" for n in r.notes)


def body_lines(r: Review, focus: str = "") -> list[str]:
    comments = focused(r, focus)
    lines = [headline(r)]
    if r.summary:
        lines.append(clean(r.summary))
    if r.other_refs:
        lines.append("Also referenced: " + ", ".join(r.other_refs))
    if line := criteria_line(r):
        lines.append(line)
    if r.scope_creep:
        lines.append(f"Out of scope: {len(r.scope_creep)} files ({', '.join(r.scope_creep)}) = {r.scope_percent}% of "
                     "changed lines")
    wanted = focus or r.focus
    head = f"Comments ({_counts(comments)})" + (f", {wanted} only" if wanted else "")
    lines.append(head + (":" if comments else ""))
    lines += comment_lines(comments)
    if r.similar:
        lines.append("Similar PRs: " + ", ".join(f"{s['pr']} ({s['overlap']})" for s in r.similar))
    lines.append(coverage_line(r))
    return lines


def card(r: Review, focus: str = "") -> str:
    lines = body_lines(r, focus)
    if r.number and not r.pasted:
        lines.append(OFFER)
    return "\n\n".join(lines)


def comment_body(r: Review) -> str:
    return strip_mentions("\n\n".join([*body_lines(r), FOOTER]))


def criteria_view(r: Review) -> str:
    rows = ["| id | criterion | status | evidence |", "|---|---|---|---|"]
    for c in r.criteria_objs():
        ev = ", ".join(f"{f}:{n}" for f, n in c.evidence) or "-"
        rows.append(f"| {c.id} | {clean(c.text).replace('|', '/')} | {_STATUS.get(c.status, c.status)} | {ev} |")
    if len(rows) == 2:
        return f"No criteria for {r.pr_label}: alignment is {_LABELS.get(r.label, r.label)}."
    searched = ", ".join(r.reviewed) or "none"
    return "\n".join([f"Criteria of {r.ticket or 'the ticket'} against {r.pr_label}:", "", *rows, "",
                      f"Files searched for evidence: {searched}."])


def similar_view(r: Review) -> str:
    if not r.similar:
        return f"No similar merged pull request shared at least 25% of its changed files with {r.pr_label}."
    return "\n".join([f"Similar merged pull requests for {r.pr_label} (file overlap, computed in code):",
                      *(f"- {s['pr']} \"{clean(s.get('title') or '')}\" ({s['overlap']})" for s in r.similar)])


def envelope(r: Review, focus: str = "") -> dict:
    comments = [c.to_dict() for c in focused(r, focus)]
    return {"summary": r.summary, "items": comments, "confidence": r.confidence, "needs_human": r.needs_human,
            "comments": comments,
            "ticket_alignment": {"label": r.label, "ticket": r.ticket or None, "coverage": r.coverage,
                                 "criteria": list(r.criteria), "scope_creep": list(r.scope_creep),
                                 "similar": [{"pr": s["pr"], "overlap": s["overlap"]} for s in r.similar]}}


def as_json(env: dict) -> str:
    return "```json\n" + json.dumps(env, indent=2) + "\n```"
